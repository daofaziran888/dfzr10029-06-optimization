from app.versioning import payload_hash as _payload_hash  # noqa: E402

_MAPPING_ROWS = SEED_ROWS["dimension_member_mapping"]
_REFRESH_ROWS = SEED_ROWS["dataset_refresh"]
_CHECKPOINT_ROWS = SEED_ROWS["dimension_refresh_checkpoint"]
_VERSIONS = ["MAP-REGION-0001", "MAP-REGION-0002", "MAP-REGION-0003"]


def _member_state_at(version: str) -> list[dict[str, Any]]:
    """重建某个映射版本提交边界上的完整成员归属（按层级、编码稳定排序）。"""
    seq = int(version.rsplit("-", 1)[1])
    states: list[dict[str, Any]] = []
    for row in _MAPPING_ROWS:
        first_seq = int(str(row["首次写入版本"]).rsplit("-", 1)[1])
        if first_seq > seq:
            continue  # 该成员在此版本之后才出现
        states.append({
            "维度编号": row["维度编号"], "维度名称": row["维度名称"],
            "成员编码": row["成员编码"], "成员名称": row["成员名称"],
            "父级编码": row["父级编码"], "父级名称": row["父级名称"],
            "层级": row["层级"],
        })
    return sorted(states, key=lambda m: (int(m["层级"]), m["成员编码"]))


for _idx, _version in enumerate(_VERSIONS, start=1):
    _snapshot = _member_state_at(_version)
    _checkpoint = next(c for c in _CHECKPOINT_ROWS if c["映射版本"] == _version)
    _checkpoint["版本成员快照"] = _snapshot
    _refresh = next(r for r in _REFRESH_ROWS if r["映射版本"] == _version)
    # 摘要只看「编码->父级编码」，与服务层幂等判断口径完全一致
    _refresh["输入摘要"] = _payload_hash(
        "DIME-0001",
        [{"成员编码": m["成员编码"], "父级编码": m["父级编码"]} for m in _snapshot],
    )


